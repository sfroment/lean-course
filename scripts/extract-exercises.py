#!/usr/bin/env python3
"""Extract every <pre data-exercise="NNNN:k"> block from lessons/*.html into
assets/exercises.js (window.EXERCISES) so the Write pad can offer them all.

Run after editing lessons:  python3 scripts/extract-exercises.py
"""
import html
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
PRE_RE = re.compile(r'<pre data-exercise="([^"]+)"[^>]*><code>(.*?)</code></pre>', re.S)

lessons = sorted((ROOT / "lessons").glob("*.html"))
exercises = []
for lesson in lessons:
    num = lesson.name.split("-")[0]
    for ex_id, body in PRE_RE.findall(lesson.read_text()):
        code = html.unescape(body).strip("\n")
        exercises.append({
            "id": ex_id,
            "lesson": num,
            "file": lesson.name,
            "ex": int(ex_id.split(":")[1]),
            "code": code,
        })

out = ROOT / "assets" / "exercises.js"
out.write_text(
    "/* Generated by scripts/extract-exercises.py — do not edit by hand.\n"
    "   Each exercise's `code` is the statement with a `sorry` hole to fill in the Write pad. */\n"
    "window.EXERCISES = " + json.dumps(exercises, indent=2, ensure_ascii=False) + ";\n"
)
print(f"wrote {out} with {len(exercises)} exercises")
